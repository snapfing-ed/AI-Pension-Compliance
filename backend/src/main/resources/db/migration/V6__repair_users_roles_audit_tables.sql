
-- V6: Corrective migration for users, roles and audit tables.
-- V5 was recorded by Flyway but its expected objects were not created.
-- This migration preserves V5 history and applies the missing changes.

-- 1. Application user accounts
CREATE TABLE app_user (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(80) NOT NULL UNIQUE,
    institutional_email VARCHAR(254) NOT NULL UNIQUE,
    display_name VARCHAR(150) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    account_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login_at TIMESTAMPTZ,

    CONSTRAINT chk_app_user_status
        CHECK (account_status IN ('PENDING', 'ACTIVE', 'LOCKED', 'DISABLED'))
);

-- 2. Application roles
CREATE TABLE app_role (
    role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_code VARCHAR(50) NOT NULL UNIQUE,
    role_name VARCHAR(100) NOT NULL,
    description TEXT,
    is_system_role BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 3. User-role assignments
CREATE TABLE user_role (
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    assigned_by_user_id BIGINT,

    CONSTRAINT pk_user_role PRIMARY KEY (user_id, role_id),

    CONSTRAINT fk_user_role_user
        FOREIGN KEY (user_id) REFERENCES app_user(user_id),

    CONSTRAINT fk_user_role_role
        FOREIGN KEY (role_id) REFERENCES app_role(role_id),

    CONSTRAINT fk_user_role_assigned_by
        FOREIGN KEY (assigned_by_user_id) REFERENCES app_user(user_id)
);

-- 4. Audit events
CREATE TABLE audit_event (
    audit_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT,
    event_type VARCHAR(80) NOT NULL,
    entity_type VARCHAR(80) NOT NULL,
    entity_id VARCHAR(100),
    action_summary TEXT NOT NULL,
    event_timestamp TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    source_ip INET,

    CONSTRAINT fk_audit_event_actor
        FOREIGN KEY (actor_user_id) REFERENCES app_user(user_id)
);

-- 5. Connect existing user-reference columns

ALTER TABLE payment_allocation
    ADD CONSTRAINT fk_payment_allocation_user
    FOREIGN KEY (allocated_by_user_id) REFERENCES app_user(user_id);

ALTER TABLE completeness_assessment
    ADD CONSTRAINT fk_completeness_assessment_user
    FOREIGN KEY (assessed_by_user_id) REFERENCES app_user(user_id);

ALTER TABLE case_finding
    ADD CONSTRAINT fk_case_finding_user
    FOREIGN KEY (linked_by_user_id) REFERENCES app_user(user_id);

ALTER TABLE case_data_quality_finding
    ADD CONSTRAINT fk_case_data_quality_finding_user
    FOREIGN KEY (linked_by_user_id) REFERENCES app_user(user_id);

ALTER TABLE investigation_case
    ADD CONSTRAINT fk_investigation_case_creator
    FOREIGN KEY (created_by_user_id) REFERENCES app_user(user_id);

ALTER TABLE case_assignment_history
    ADD CONSTRAINT fk_case_assignment_assigned_user
    FOREIGN KEY (assigned_user_id) REFERENCES app_user(user_id);

ALTER TABLE case_assignment_history
    ADD CONSTRAINT fk_case_assignment_assigned_by
    FOREIGN KEY (assigned_by_user_id) REFERENCES app_user(user_id);

-- 6. Record the user who initiated an analysis snapshot
ALTER TABLE analysis_snapshot
    ADD CONSTRAINT fk_analysis_snapshot_creator
    FOREIGN KEY (created_by_user_id) REFERENCES app_user(user_id);

-- 7. Indexes
CREATE INDEX idx_app_user_status
    ON app_user(account_status);

CREATE INDEX idx_user_role_role
    ON user_role(role_id);

CREATE INDEX idx_audit_event_actor
    ON audit_event(actor_user_id);

CREATE INDEX idx_audit_event_timestamp
    ON audit_event(event_timestamp);

CREATE INDEX idx_audit_event_entity
    ON audit_event(entity_type, entity_id);

