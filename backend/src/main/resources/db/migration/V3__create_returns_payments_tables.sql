
-- SMARTCOMPLIANCE V3
-- Returns, payments and completeness evidence

CREATE TABLE submitted_return (
    return_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    employer_id BIGINT NOT NULL,
    period_id BIGINT NOT NULL,
    return_type VARCHAR(40) NOT NULL,
    return_ref VARCHAR(100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_submitted_return PRIMARY KEY (return_id),
    CONSTRAINT uq_submitted_return_context
        UNIQUE (return_id, employer_id, period_id),

    CONSTRAINT fk_return_employer
        FOREIGN KEY (employer_id) REFERENCES employer(employer_id),
    CONSTRAINT fk_return_period
        FOREIGN KEY (period_id) REFERENCES contribution_period(period_id),

    CONSTRAINT ck_return_type
        CHECK (return_type IN (
            'STANDARD', 'AMENDED', 'SUPPLEMENTARY', 'OTHER'
        ))
);

CREATE INDEX idx_return_employer_period
    ON submitted_return(employer_id, period_id);


CREATE TABLE return_version (
    return_version_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    return_id BIGINT NOT NULL,
    source_id BIGINT NOT NULL,
    version_no INTEGER NOT NULL,
    submitted_at TIMESTAMPTZ,
    received_at TIMESTAMPTZ NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reported_employee_amount NUMERIC(15,2),
    reported_employer_amount NUMERIC(15,2),
    reported_total_amount NUMERIC(15,2),
    completeness_status VARCHAR(20) NOT NULL DEFAULT 'UNKNOWN',
    supersedes_version_id BIGINT,
    source_document_ref VARCHAR(150),

    CONSTRAINT pk_return_version PRIMARY KEY (return_version_id),
    CONSTRAINT uq_return_version_no UNIQUE (return_id, version_no),
    CONSTRAINT uq_return_version_context
        UNIQUE (return_version_id, return_id),

    CONSTRAINT fk_return_version_return
        FOREIGN KEY (return_id) REFERENCES submitted_return(return_id),
    CONSTRAINT fk_return_version_source
        FOREIGN KEY (source_id) REFERENCES data_source(source_id),
    CONSTRAINT fk_return_version_supersedes
        FOREIGN KEY (supersedes_version_id)
        REFERENCES return_version(return_version_id),

    CONSTRAINT ck_return_version_no CHECK (version_no > 0),
    CONSTRAINT ck_return_amounts CHECK (
        (reported_employee_amount IS NULL OR reported_employee_amount >= 0)
        AND (reported_employer_amount IS NULL OR reported_employer_amount >= 0)
        AND (reported_total_amount IS NULL OR reported_total_amount >= 0)
    ),
    CONSTRAINT ck_return_completeness
        CHECK (completeness_status IN (
            'UNKNOWN', 'COMPLETE', 'INCOMPLETE', 'INVALID'
        ))
);

CREATE INDEX idx_return_version_received
    ON return_version(return_id, received_at DESC);


CREATE TABLE return_line (
    return_line_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    return_version_id BIGINT NOT NULL,
    member_id BIGINT,
    line_ref VARCHAR(100),
    reported_pay NUMERIC(15,2),
    reported_employee_amount NUMERIC(15,2),
    reported_employer_amount NUMERIC(15,2),
    reported_total_amount NUMERIC(15,2),
    line_status VARCHAR(20) NOT NULL DEFAULT 'UNVERIFIED',

    CONSTRAINT pk_return_line PRIMARY KEY (return_line_id),
    CONSTRAINT fk_return_line_version
        FOREIGN KEY (return_version_id)
        REFERENCES return_version(return_version_id),
    CONSTRAINT fk_return_line_member
        FOREIGN KEY (member_id) REFERENCES member(member_id),

    CONSTRAINT ck_return_line_amounts CHECK (
        (reported_pay IS NULL OR reported_pay >= 0)
        AND (reported_employee_amount IS NULL OR reported_employee_amount >= 0)
        AND (reported_employer_amount IS NULL OR reported_employer_amount >= 0)
        AND (reported_total_amount IS NULL OR reported_total_amount >= 0)
    ),
    CONSTRAINT ck_return_line_status
        CHECK (line_status IN (
            'UNVERIFIED', 'VALID', 'INCOMPLETE', 'INVALID'
        ))
);

CREATE UNIQUE INDEX uq_return_line_ref
    ON return_line(return_version_id, line_ref)
    WHERE line_ref IS NOT NULL;

CREATE INDEX idx_return_line_member
    ON return_line(member_id);


CREATE TABLE payment_transaction (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    source_id BIGINT NOT NULL,
    external_transaction_ref VARCHAR(150),
    employer_ref_as_received VARCHAR(100),
    transaction_amount NUMERIC(15,2) NOT NULL,
    currency_code CHAR(3) NOT NULL DEFAULT 'ZMW',
    paid_at TIMESTAMPTZ,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    transaction_status VARCHAR(20) NOT NULL DEFAULT 'RECEIVED',
    reversal_of_payment_id BIGINT,
    source_record_ref VARCHAR(150),

    CONSTRAINT pk_payment_transaction PRIMARY KEY (payment_id),
    CONSTRAINT fk_payment_source
        FOREIGN KEY (source_id) REFERENCES data_source(source_id),
    CONSTRAINT fk_payment_reversal
        FOREIGN KEY (reversal_of_payment_id)
        REFERENCES payment_transaction(payment_id),

    CONSTRAINT ck_payment_amount
        CHECK (transaction_amount > 0),
    CONSTRAINT ck_payment_status
        CHECK (transaction_status IN (
            'RECEIVED', 'CONFIRMED', 'REVERSED', 'REJECTED', 'PENDING'
        )),
    CONSTRAINT ck_payment_not_self_reversal
        CHECK (reversal_of_payment_id IS NULL
               OR reversal_of_payment_id <> payment_id)
);

CREATE UNIQUE INDEX uq_payment_external_ref
    ON payment_transaction(source_id, external_transaction_ref)
    WHERE external_transaction_ref IS NOT NULL;

CREATE INDEX idx_payment_paid_at
    ON payment_transaction(paid_at);


CREATE TABLE payment_allocation (
    allocation_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    payment_id BIGINT NOT NULL,
    analysis_id BIGINT NOT NULL,
    allocated_amount NUMERIC(15,2) NOT NULL,
    allocation_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    allocated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    allocated_by_user_id BIGINT,
    reverses_allocation_id BIGINT,

    CONSTRAINT pk_payment_allocation PRIMARY KEY (allocation_id),
    CONSTRAINT fk_allocation_payment
        FOREIGN KEY (payment_id) REFERENCES payment_transaction(payment_id),
    CONSTRAINT fk_allocation_analysis
        FOREIGN KEY (analysis_id) REFERENCES employer_month_analysis(analysis_id),
    CONSTRAINT fk_allocation_reversal
        FOREIGN KEY (reverses_allocation_id)
        REFERENCES payment_allocation(allocation_id),

    CONSTRAINT ck_allocation_amount CHECK (allocated_amount > 0),
    CONSTRAINT ck_allocation_status
        CHECK (allocation_status IN (
            'ACTIVE', 'REVERSED', 'PENDING', 'REJECTED'
        )),
    CONSTRAINT ck_allocation_not_self_reversal
        CHECK (reverses_allocation_id IS NULL
               OR reverses_allocation_id <> allocation_id)
);

CREATE INDEX idx_allocation_analysis
    ON payment_allocation(analysis_id);

CREATE INDEX idx_allocation_payment
    ON payment_allocation(payment_id);


CREATE TABLE completeness_assessment (
    assessment_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    source_id BIGINT NOT NULL,
    scope_type VARCHAR(30) NOT NULL,
    scope_start DATE NOT NULL,
    scope_end DATE NOT NULL,
    employer_id BIGINT,
    period_id BIGINT,
    assessment_status VARCHAR(20) NOT NULL,
    assessed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    assessed_by_user_id BIGINT,
    evidence_notes TEXT,

    CONSTRAINT pk_completeness_assessment PRIMARY KEY (assessment_id),
    CONSTRAINT fk_completeness_source
        FOREIGN KEY (source_id) REFERENCES data_source(source_id),
    CONSTRAINT fk_completeness_employer
        FOREIGN KEY (employer_id) REFERENCES employer(employer_id),
    CONSTRAINT fk_completeness_period
        FOREIGN KEY (period_id) REFERENCES contribution_period(period_id),

    CONSTRAINT ck_completeness_scope_dates
        CHECK (scope_start <= scope_end),
    CONSTRAINT ck_completeness_scope_type
        CHECK (scope_type IN (
            'GLOBAL', 'EMPLOYER', 'PERIOD', 'EMPLOYER_PERIOD'
        )),
    CONSTRAINT ck_completeness_scope_reference
        CHECK (
            (scope_type = 'GLOBAL'
                AND employer_id IS NULL AND period_id IS NULL)
            OR
            (scope_type = 'EMPLOYER'
                AND employer_id IS NOT NULL AND period_id IS NULL)
            OR
            (scope_type = 'PERIOD'
                AND employer_id IS NULL AND period_id IS NOT NULL)
            OR
            (scope_type = 'EMPLOYER_PERIOD'
                AND employer_id IS NOT NULL AND period_id IS NOT NULL)
        ),
    CONSTRAINT ck_completeness_status
        CHECK (assessment_status IN (
            'COMPLETE', 'PARTIAL', 'INCOMPLETE', 'UNKNOWN'
        ))
);

CREATE INDEX idx_completeness_source_scope
    ON completeness_assessment(source_id, scope_start, scope_end);


CREATE TABLE snapshot_return_version (
    snapshot_id BIGINT NOT NULL,
    return_version_id BIGINT NOT NULL,

    CONSTRAINT pk_snapshot_return_version
        PRIMARY KEY (snapshot_id, return_version_id),
    CONSTRAINT fk_srv_snapshot
        FOREIGN KEY (snapshot_id) REFERENCES analysis_snapshot(snapshot_id),
    CONSTRAINT fk_srv_return_version
        FOREIGN KEY (return_version_id)
        REFERENCES return_version(return_version_id)
);


CREATE TABLE snapshot_payment_allocation (
    snapshot_id BIGINT NOT NULL,
    allocation_id BIGINT NOT NULL,

    CONSTRAINT pk_snapshot_payment_allocation
        PRIMARY KEY (snapshot_id, allocation_id),
    CONSTRAINT fk_spa_snapshot
        FOREIGN KEY (snapshot_id) REFERENCES analysis_snapshot(snapshot_id),
    CONSTRAINT fk_spa_allocation
        FOREIGN KEY (allocation_id)
        REFERENCES payment_allocation(allocation_id)
);


CREATE TABLE snapshot_completeness_assessment (
    snapshot_id BIGINT NOT NULL,
    assessment_id BIGINT NOT NULL,

    CONSTRAINT pk_snapshot_completeness_assessment
        PRIMARY KEY (snapshot_id, assessment_id),
    CONSTRAINT fk_sca_snapshot
        FOREIGN KEY (snapshot_id) REFERENCES analysis_snapshot(snapshot_id),
    CONSTRAINT fk_sca_assessment
        FOREIGN KEY (assessment_id)
        REFERENCES completeness_assessment(assessment_id)
);


-- Supporting indexes for snapshot evidence lookups
CREATE INDEX idx_snapshot_return_version_return
    ON snapshot_return_version(return_version_id);

CREATE INDEX idx_snapshot_payment_allocation_allocation
    ON snapshot_payment_allocation(allocation_id);

CREATE INDEX idx_snapshot_completeness_assessment_assessment
    ON snapshot_completeness_assessment(assessment_id);
