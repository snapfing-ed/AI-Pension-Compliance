
-- SMARTCOMPLIANCE V4
-- Findings and investigation workflow

CREATE TABLE data_quality_finding (
    dq_finding_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    snapshot_id BIGINT NOT NULL,
    finding_code VARCHAR(100) NOT NULL,
    description TEXT NOT NULL,
    severity VARCHAR(20) NOT NULL,
    affected_record_type VARCHAR(50) NOT NULL,
    affected_payroll_record_id BIGINT,
    affected_return_line_id BIGINT,
    affected_payment_id BIGINT,
    detected_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolution_status VARCHAR(20) NOT NULL DEFAULT 'OPEN',

    CONSTRAINT pk_data_quality_finding PRIMARY KEY (dq_finding_id),
    CONSTRAINT fk_dq_finding_snapshot
        FOREIGN KEY (snapshot_id)
        REFERENCES analysis_snapshot(snapshot_id),
    CONSTRAINT fk_dq_finding_payroll
        FOREIGN KEY (affected_payroll_record_id)
        REFERENCES payroll_record(payroll_record_id),
    CONSTRAINT fk_dq_finding_return_line
        FOREIGN KEY (affected_return_line_id)
        REFERENCES return_line(return_line_id),
    CONSTRAINT fk_dq_finding_payment
        FOREIGN KEY (affected_payment_id)
        REFERENCES payment_transaction(payment_id),

    CONSTRAINT ck_dq_severity
        CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_dq_resolution
        CHECK (resolution_status IN (
            'OPEN', 'UNDER_REVIEW', 'RESOLVED', 'ACCEPTED'
        )),
    CONSTRAINT ck_dq_affected_record
        CHECK (
            (CASE WHEN affected_payroll_record_id IS NOT NULL THEN 1 ELSE 0 END)
          + (CASE WHEN affected_return_line_id IS NOT NULL THEN 1 ELSE 0 END)
          + (CASE WHEN affected_payment_id IS NOT NULL THEN 1 ELSE 0 END)
          <= 1
        )
);

CREATE INDEX idx_dq_finding_snapshot
    ON data_quality_finding(snapshot_id);

CREATE INDEX idx_dq_finding_status
    ON data_quality_finding(resolution_status);


CREATE TABLE compliance_finding (
    finding_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    snapshot_id BIGINT NOT NULL,
    finding_code VARCHAR(100) NOT NULL,
    category VARCHAR(40) NOT NULL,
    description TEXT NOT NULL,
    priority_score NUMERIC(8,3),
    confidence_score NUMERIC(6,5),
    detection_method VARCHAR(30) NOT NULL,
    explanation TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'NEW',
    detected_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_compliance_finding PRIMARY KEY (finding_id),
    CONSTRAINT fk_compliance_finding_snapshot
        FOREIGN KEY (snapshot_id)
        REFERENCES analysis_snapshot(snapshot_id),

    CONSTRAINT ck_compliance_category
        CHECK (category IN (
            'POTENTIALLY_MISSING',
            'POTENTIALLY_DELAYED',
            'POTENTIALLY_INCOMPLETE',
            'UNUSUAL_PATTERN',
            'OTHER'
        )),
    CONSTRAINT ck_compliance_priority
        CHECK (priority_score IS NULL OR priority_score >= 0),
    CONSTRAINT ck_compliance_confidence
        CHECK (
            confidence_score IS NULL
            OR confidence_score BETWEEN 0 AND 1
        ),
    CONSTRAINT ck_compliance_detection_method
        CHECK (detection_method IN ('RULE', 'ML', 'HYBRID', 'MANUAL')),
    CONSTRAINT ck_compliance_finding_status
        CHECK (status IN (
            'NEW', 'UNDER_REVIEW', 'CONFIRMED',
            'NOT_SUBSTANTIATED', 'RESOLVED'
        ))
);

CREATE INDEX idx_compliance_finding_snapshot
    ON compliance_finding(snapshot_id);

CREATE INDEX idx_compliance_finding_priority
    ON compliance_finding(priority_score DESC);

CREATE INDEX idx_compliance_finding_status
    ON compliance_finding(status);


CREATE TABLE investigation_case (
    case_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    case_ref VARCHAR(50) NOT NULL,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    case_status VARCHAR(25) NOT NULL DEFAULT 'OPEN',
    priority VARCHAR(20) NOT NULL DEFAULT 'MEDIUM',
    opened_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at TIMESTAMPTZ,
    created_by_user_id BIGINT,

    CONSTRAINT pk_investigation_case PRIMARY KEY (case_id),
    CONSTRAINT uq_investigation_case_ref UNIQUE (case_ref),

    CONSTRAINT ck_case_status
        CHECK (case_status IN (
            'OPEN', 'ASSIGNED', 'UNDER_INVESTIGATION',
            'PENDING_REVIEW', 'CLOSED', 'CANCELLED'
        )),
    CONSTRAINT ck_case_priority
        CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_case_closure
        CHECK (closed_at IS NULL OR closed_at >= opened_at)
);


CREATE TABLE case_finding (
    case_finding_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    case_id BIGINT NOT NULL,
    finding_id BIGINT NOT NULL,
    linked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    linked_by_user_id BIGINT,
    case_specific_disposition VARCHAR(30),
    notes TEXT,

    CONSTRAINT pk_case_finding PRIMARY KEY (case_finding_id),
    CONSTRAINT uq_case_finding UNIQUE (case_id, finding_id),
    CONSTRAINT fk_case_finding_case
        FOREIGN KEY (case_id) REFERENCES investigation_case(case_id),
    CONSTRAINT fk_case_finding_finding
        FOREIGN KEY (finding_id) REFERENCES compliance_finding(finding_id),

    CONSTRAINT ck_case_finding_disposition
        CHECK (
            case_specific_disposition IS NULL
            OR case_specific_disposition IN (
                'REQUIRES_REVIEW', 'CONFIRMED',
                'NOT_SUBSTANTIATED', 'RESOLVED'
            )
        )
);


CREATE TABLE case_data_quality_finding (
    case_dq_finding_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    case_id BIGINT NOT NULL,
    dq_finding_id BIGINT NOT NULL,
    linked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    linked_by_user_id BIGINT,
    notes TEXT,

    CONSTRAINT pk_case_dq_finding PRIMARY KEY (case_dq_finding_id),
    CONSTRAINT uq_case_dq_finding UNIQUE (case_id, dq_finding_id),
    CONSTRAINT fk_case_dq_case
        FOREIGN KEY (case_id) REFERENCES investigation_case(case_id),
    CONSTRAINT fk_case_dq_finding
        FOREIGN KEY (dq_finding_id)
        REFERENCES data_quality_finding(dq_finding_id)
);


CREATE TABLE case_assignment_history (
    assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    case_id BIGINT NOT NULL,
    assigned_user_id BIGINT NOT NULL,
    assigned_by_user_id BIGINT NOT NULL,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    unassigned_at TIMESTAMPTZ,
    assignment_note TEXT,

    CONSTRAINT pk_case_assignment_history PRIMARY KEY (assignment_id),
    CONSTRAINT fk_assignment_case
        FOREIGN KEY (case_id) REFERENCES investigation_case(case_id),

    CONSTRAINT ck_assignment_dates
        CHECK (unassigned_at IS NULL OR unassigned_at >= assigned_at)
);

CREATE INDEX idx_case_assignment_case
    ON case_assignment_history(case_id, assigned_at DESC);

CREATE INDEX idx_case_assignment_user
    ON case_assignment_history(assigned_user_id);

CREATE INDEX idx_case_finding_finding
    ON case_finding(finding_id);

CREATE INDEX idx_case_dq_finding
    ON case_data_quality_finding(dq_finding_id);
