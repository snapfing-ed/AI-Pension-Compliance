-- SMARTCOMPLIANCE V10
-- Additive quarantine table for invalid payroll import rows (FR-M2-12).
-- Required because V2 payroll_record enforces NOT NULL member_id and non-negative
-- eligible_gross_pay, while V4 data_quality_finding requires an analysis_snapshot
-- that does not yet exist at batch import time.

CREATE TABLE payroll_quarantine_record (
    quarantine_record_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    payroll_batch_id BIGINT NOT NULL,
    row_number INTEGER NOT NULL,
    source_row_ref TEXT,
    raw_member_ref TEXT,
    raw_source_member_ref TEXT,
    raw_eligible_gross_pay TEXT,
    raw_payroll_status TEXT,
    reason_code VARCHAR(60) NOT NULL,
    reason_detail TEXT NOT NULL,
    quarantined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_payroll_quarantine_record PRIMARY KEY (quarantine_record_id),
    CONSTRAINT fk_quarantine_payroll_batch
        FOREIGN KEY (payroll_batch_id) REFERENCES payroll_batch(payroll_batch_id),

    CONSTRAINT ck_quarantine_row_number CHECK (row_number > 0),
    CONSTRAINT ck_quarantine_reason_code CHECK (reason_code IN (
        'MISSING_MEMBER_REF',
        'INVALID_MEMBER_REF',
        'NEGATIVE_GROSS_PAY',
        'INVALID_PAY_FORMAT',
        'DUPLICATE_MEMBER_IN_BATCH',
        'DUPLICATE_SOURCE_ROW_REF',
        'INVALID_PAYROLL_STATUS',
        'INVALID_SOURCE_ROW_REF',
        'MULTIPLE_VALIDATION_ERRORS'
    ))
);

CREATE INDEX idx_quarantine_batch_row
    ON payroll_quarantine_record(payroll_batch_id, row_number);