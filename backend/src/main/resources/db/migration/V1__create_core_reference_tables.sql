-- 1. EMPLOYER
CREATE TABLE employer (
    employer_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    employer_ref VARCHAR(50) NOT NULL,
    legal_name VARCHAR(200) NOT NULL,
    trading_name VARCHAR(200),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_employer
        PRIMARY KEY (employer_id),

    CONSTRAINT uq_employer_ref
        UNIQUE (employer_ref),

    CONSTRAINT ck_employer_status
        CHECK (status IN ('ACTIVE', 'INACTIVE', 'SUSPENDED'))
);


-- 2. MEMBER
CREATE TABLE member (
    member_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    member_ref VARCHAR(50) NOT NULL,
    source_member_ref VARCHAR(100),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_member
        PRIMARY KEY (member_id),

    CONSTRAINT uq_member_ref
        UNIQUE (member_ref),

    CONSTRAINT ck_member_status
        CHECK (status IN ('ACTIVE', 'INACTIVE', 'UNKNOWN'))
);


-- 3. CONTRIBUTION PERIOD
CREATE TABLE contribution_period (
    period_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    period_year SMALLINT NOT NULL,
    period_month SMALLINT NOT NULL,
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    period_label VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN',

    CONSTRAINT pk_contribution_period
        PRIMARY KEY (period_id),

    CONSTRAINT uq_contribution_period_year_month
        UNIQUE (period_year, period_month),

    CONSTRAINT ck_contribution_period_month
        CHECK (period_month BETWEEN 1 AND 12),

    CONSTRAINT ck_contribution_period_year
        CHECK (period_year BETWEEN 2000 AND 2200),

    CONSTRAINT ck_contribution_period_dates
        CHECK (
            period_start <= period_end
            AND EXTRACT(YEAR FROM period_start) = period_year
            AND EXTRACT(MONTH FROM period_start) = period_month
            AND EXTRACT(YEAR FROM period_end) = period_year
            AND EXTRACT(MONTH FROM period_end) = period_month
        ),

    CONSTRAINT ck_contribution_period_status
        CHECK (status IN ('OPEN', 'CLOSED', 'ARCHIVED'))
);


-- 4. DATA SOURCE
CREATE TABLE data_source (
    source_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    source_name VARCHAR(150) NOT NULL,
    source_type VARCHAR(40) NOT NULL,
    owner_name VARCHAR(150),
    authority_reference VARCHAR(150),
    permitted_purpose TEXT NOT NULL,
    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    coverage_notes TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

    CONSTRAINT pk_data_source
        PRIMARY KEY (source_id),

    CONSTRAINT ck_data_source_status
        CHECK (status IN ('ACTIVE', 'INACTIVE', 'RESTRICTED'))
);


-- 5. CONTRIBUTION RULE VERSION
CREATE TABLE contribution_rule_version (
    rule_version_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    rule_code VARCHAR(50) NOT NULL,
    version_no INTEGER NOT NULL,
    effective_from DATE NOT NULL,
    effective_to DATE,
    employee_rate NUMERIC(9,6) NOT NULL,
    employer_rate NUMERIC(9,6) NOT NULL,
    ceiling_amount NUMERIC(15,2),
    due_day_rule VARCHAR(100) NOT NULL,
    rounding_rule VARCHAR(50) NOT NULL,
    source_reference TEXT NOT NULL,
    verification_status VARCHAR(30) NOT NULL DEFAULT 'UNVERIFIED',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_contribution_rule_version
        PRIMARY KEY (rule_version_id),

    CONSTRAINT uq_contribution_rule_version
        UNIQUE (rule_code, version_no),

    CONSTRAINT ck_contribution_rule_version_no
        CHECK (version_no > 0),

    CONSTRAINT ck_contribution_rule_dates
        CHECK (
            effective_to IS NULL
            OR effective_to >= effective_from
        ),

    CONSTRAINT ck_employee_rate
        CHECK (employee_rate BETWEEN 0 AND 1),

    CONSTRAINT ck_employer_rate
        CHECK (employer_rate BETWEEN 0 AND 1),

    CONSTRAINT ck_contribution_ceiling
        CHECK (
            ceiling_amount IS NULL
            OR ceiling_amount > 0
        ),

    CONSTRAINT ck_contribution_rule_verification
        CHECK (
            verification_status IN (
                'UNVERIFIED',
                'VERIFIED',
                'REJECTED'
            )
        )
);


