
-- SMARTCOMPLIANCE V2
-- Payroll and analysis foundation

CREATE TABLE payroll_batch (
    payroll_batch_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    employer_id BIGINT NOT NULL,
    period_id BIGINT NOT NULL,
    source_id BIGINT NOT NULL,
    batch_ref VARCHAR(100) NOT NULL,
    version_no INTEGER NOT NULL,
    received_at TIMESTAMPTZ NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) NOT NULL DEFAULT 'RECEIVED',
    supersedes_batch_id BIGINT,

    CONSTRAINT pk_payroll_batch PRIMARY KEY (payroll_batch_id),
    CONSTRAINT uq_payroll_batch_version
        UNIQUE (source_id, batch_ref, version_no),
    CONSTRAINT uq_payroll_batch_context
        UNIQUE (payroll_batch_id, employer_id, period_id),

    CONSTRAINT fk_payroll_batch_employer
        FOREIGN KEY (employer_id) REFERENCES employer(employer_id),
    CONSTRAINT fk_payroll_batch_period
        FOREIGN KEY (period_id) REFERENCES contribution_period(period_id),
    CONSTRAINT fk_payroll_batch_source
        FOREIGN KEY (source_id) REFERENCES data_source(source_id),
    CONSTRAINT fk_payroll_batch_supersedes
        FOREIGN KEY (supersedes_batch_id)
        REFERENCES payroll_batch(payroll_batch_id),

    CONSTRAINT ck_payroll_batch_version CHECK (version_no > 0),
    CONSTRAINT ck_payroll_batch_status
        CHECK (status IN ('RECEIVED', 'VALIDATED', 'REJECTED', 'SUPERSEDED'))
);

CREATE TABLE payroll_record (
    payroll_record_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    payroll_batch_id BIGINT NOT NULL,
    employer_id BIGINT NOT NULL,
    member_id BIGINT NOT NULL,
    period_id BIGINT NOT NULL,
    source_row_ref VARCHAR(100),
    eligible_gross_pay NUMERIC(15,2),
    payroll_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    data_quality_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',

    CONSTRAINT pk_payroll_record PRIMARY KEY (payroll_record_id),
    CONSTRAINT uq_payroll_record_context
        UNIQUE (payroll_record_id, payroll_batch_id),

    CONSTRAINT fk_payroll_record_batch_context
        FOREIGN KEY (payroll_batch_id, employer_id, period_id)
        REFERENCES payroll_batch(payroll_batch_id, employer_id, period_id),
    CONSTRAINT fk_payroll_record_member
        FOREIGN KEY (member_id) REFERENCES member(member_id),

    CONSTRAINT ck_payroll_gross_pay
        CHECK (eligible_gross_pay IS NULL OR eligible_gross_pay >= 0),
    CONSTRAINT ck_payroll_record_status
        CHECK (payroll_status IN ('ACTIVE', 'INACTIVE', 'REVERSED')),
    CONSTRAINT ck_payroll_quality_status
        CHECK (data_quality_status IN ('PENDING', 'VALID', 'ISSUE'))
);

CREATE UNIQUE INDEX uq_payroll_record_source_row
    ON payroll_record(payroll_batch_id, source_row_ref)
    WHERE source_row_ref IS NOT NULL;

CREATE TABLE employer_month_analysis (
    analysis_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    employer_id BIGINT NOT NULL,
    period_id BIGINT NOT NULL,
    current_status VARCHAR(30) NOT NULL DEFAULT 'NOT_ANALYSED',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_employer_month_analysis PRIMARY KEY (analysis_id),
    CONSTRAINT uq_employer_month_analysis
        UNIQUE (employer_id, period_id),
    CONSTRAINT fk_analysis_employer
        FOREIGN KEY (employer_id) REFERENCES employer(employer_id),
    CONSTRAINT fk_analysis_period
        FOREIGN KEY (period_id) REFERENCES contribution_period(period_id),
    CONSTRAINT ck_analysis_status
        CHECK (current_status IN (
            'NOT_ANALYSED', 'UNDER_REVIEW', 'REQUIRES_INVESTIGATION',
            'NO_ISSUE_DETECTED', 'DATA_INCOMPLETE'
        ))
);

CREATE TABLE analysis_snapshot (
    snapshot_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    analysis_id BIGINT NOT NULL,
    run_number INTEGER NOT NULL,
    run_started_at TIMESTAMPTZ NOT NULL,
    run_completed_at TIMESTAMPTZ,
    rule_version_id BIGINT NOT NULL,
    model_name VARCHAR(100),
    model_version VARCHAR(50),
    detection_logic_version VARCHAR(50) NOT NULL,
    input_fingerprint VARCHAR(128) NOT NULL,
    overall_result VARCHAR(30) NOT NULL,
    created_by_user_id BIGINT,

    CONSTRAINT pk_analysis_snapshot PRIMARY KEY (snapshot_id),
    CONSTRAINT uq_analysis_snapshot_run
        UNIQUE (analysis_id, run_number),
    CONSTRAINT uq_snapshot_rule
        UNIQUE (snapshot_id, rule_version_id),

    CONSTRAINT fk_snapshot_analysis
        FOREIGN KEY (analysis_id)
        REFERENCES employer_month_analysis(analysis_id),
    CONSTRAINT fk_snapshot_rule
        FOREIGN KEY (rule_version_id)
        REFERENCES contribution_rule_version(rule_version_id),

    CONSTRAINT ck_snapshot_run_number CHECK (run_number > 0),
    CONSTRAINT ck_snapshot_timestamps
        CHECK (run_completed_at IS NULL OR run_completed_at >= run_started_at),
    CONSTRAINT ck_snapshot_result
        CHECK (overall_result IN (
            'PENDING', 'NO_ISSUE_DETECTED', 'REQUIRES_REVIEW',
            'DATA_INCOMPLETE', 'FAILED'
        ))
);

CREATE TABLE snapshot_payroll_batch (
    snapshot_id BIGINT NOT NULL,
    payroll_batch_id BIGINT NOT NULL,

    CONSTRAINT pk_snapshot_payroll_batch
        PRIMARY KEY (snapshot_id, payroll_batch_id),
    CONSTRAINT fk_spb_snapshot
        FOREIGN KEY (snapshot_id)
        REFERENCES analysis_snapshot(snapshot_id),
    CONSTRAINT fk_spb_batch
        FOREIGN KEY (payroll_batch_id)
        REFERENCES payroll_batch(payroll_batch_id)
);

CREATE TABLE contribution_calculation (
    calculation_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    snapshot_id BIGINT NOT NULL,
    payroll_record_id BIGINT NOT NULL,
    payroll_batch_id BIGINT NOT NULL,
    rule_version_id BIGINT NOT NULL,
    eligible_pay_used NUMERIC(15,2) NOT NULL,
    employee_expected NUMERIC(15,2) NOT NULL,
    employer_expected NUMERIC(15,2) NOT NULL,
    total_expected NUMERIC(15,2) NOT NULL,
    calculation_status VARCHAR(20) NOT NULL,
    explanation_code VARCHAR(100),

    CONSTRAINT pk_contribution_calculation PRIMARY KEY (calculation_id),
    CONSTRAINT uq_calculation_record
        UNIQUE (snapshot_id, payroll_record_id),

    CONSTRAINT fk_calculation_snapshot_batch
        FOREIGN KEY (snapshot_id, payroll_batch_id)
        REFERENCES snapshot_payroll_batch(snapshot_id, payroll_batch_id),
    CONSTRAINT fk_calculation_payroll_record
        FOREIGN KEY (payroll_record_id, payroll_batch_id)
        REFERENCES payroll_record(payroll_record_id, payroll_batch_id),
    CONSTRAINT fk_calculation_snapshot_rule
        FOREIGN KEY (snapshot_id, rule_version_id)
        REFERENCES analysis_snapshot(snapshot_id, rule_version_id),

    CONSTRAINT ck_calculation_amounts CHECK (
        eligible_pay_used >= 0
        AND employee_expected >= 0
        AND employer_expected >= 0
        AND total_expected >= 0
    ),
    CONSTRAINT ck_calculation_total
        CHECK (total_expected = employee_expected + employer_expected),
    CONSTRAINT ck_calculation_status
        CHECK (calculation_status IN ('CALCULATED', 'INVALID', 'EXCLUDED'))
);

CREATE INDEX idx_payroll_batch_employer_period
    ON payroll_batch(employer_id, period_id);

CREATE INDEX idx_payroll_record_member
    ON payroll_record(member_id);

CREATE INDEX idx_analysis_snapshot_analysis
    ON analysis_snapshot(analysis_id, run_number);

CREATE INDEX idx_calculation_snapshot
    ON contribution_calculation(snapshot_id);
